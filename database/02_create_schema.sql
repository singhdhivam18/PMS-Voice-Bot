CREATE OR REPLACE FUNCTION public.normalize_in_phone(p text)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
    SELECT CASE
        WHEN d ~ '^[6-9][0-9]{9}$'
            THEN '+91' || d
        WHEN d ~ '^91[6-9][0-9]{9}$'
            THEN '+' || d
        WHEN d ~ '^0[6-9][0-9]{9}$'
            THEN '+91' || substr(d, 2)
        ELSE NULL
    END
    FROM (
        SELECT regexp_replace(
            coalesce(p, ''),
            '\\D',
            '',
            'g'
        ) AS d
    ) s;
$$;

CREATE OR REPLACE FUNCTION public.assign_vehicle(
    p_vehicle_id bigint,
    p_driver_id bigint,
    p_at timestamp with time zone DEFAULT now()
)
RETURNS bigint
LANGUAGE plpgsql
AS $$
DECLARE
    v_current_id     bigint;
    v_current_driver bigint;
    v_new_id         bigint;
BEGIN
    SELECT id, driver_id
    INTO v_current_id, v_current_driver
    FROM public.vehicle_assignment
    WHERE vehicle_id = p_vehicle_id
      AND assigned_to IS NULL
    FOR UPDATE;

    -- Already assigned to this driver.
    IF v_current_id IS NOT NULL
       AND v_current_driver = p_driver_id THEN
        RETURN v_current_id;
    END IF;

    -- Close previous assignment.
    IF v_current_id IS NOT NULL THEN
        UPDATE public.vehicle_assignment
        SET assigned_to = p_at
        WHERE id = v_current_id;
    END IF;

    -- Create new assignment.
    INSERT INTO public.vehicle_assignment
    (
        vehicle_id,
        driver_id,
        assigned_from
    )
    VALUES
    (
        p_vehicle_id,
        p_driver_id,
        p_at
    )
    RETURNING id INTO v_new_id;

    RETURN v_new_id;
END;
$$;

