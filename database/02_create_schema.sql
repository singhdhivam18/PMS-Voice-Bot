-- PostgreSQL schema creation for dev-voice-db
-- Source: Dev_voice_db2.sql
-- Run after 01_create_database.sql while connected to dev-voice-db.

BEGIN;

CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA public;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA public;

-- ============================================================
-- TABLES
-- ============================================================

CREATE TABLE public.language (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(50) NOT NULL,
    code character varying(5) NOT NULL,
    created_at timestamp(6) without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_language_name UNIQUE (name),
    CONSTRAINT uq_language_code UNIQUE (code)
);

CREATE TABLE public.driver (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id uuid DEFAULT gen_random_uuid() NOT NULL,
    name character varying(100) NOT NULL,
    phone character varying(20) NOT NULL,
    preferred_language_id smallint NOT NULL,
    language_source character varying(10) DEFAULT 'default'::character varying NOT NULL,
    do_not_call boolean DEFAULT false NOT NULL,
    created_at timestamp(6) without time zone DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'::text) NOT NULL,
    updated_at timestamp(6) without time zone DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'::text) NOT NULL,
    CONSTRAINT ck_driver_language_source CHECK (
        language_source IN ('default', 'manual', 'detected')
    ),
    CONSTRAINT ck_driver_phone_e164 CHECK (
        phone::text ~ '^\\+[1-9][0-9]{7,14}$'
    ),
    CONSTRAINT uq_driver_external_id UNIQUE (external_id),
    CONSTRAINT uq_driver_phone UNIQUE (phone),
    CONSTRAINT fk_driver_language FOREIGN KEY (preferred_language_id)
        REFERENCES public.language(id)
);

CREATE TABLE public.vehicle (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id uuid DEFAULT gen_random_uuid() NOT NULL,
    registration_no character varying(20) NOT NULL,
    created_at timestamp(6) without time zone DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'::text) NOT NULL,
    driver_id bigint,
    is_active boolean DEFAULT true NOT NULL,
    CONSTRAINT uq_vehicle_registration_no UNIQUE (registration_no),
    CONSTRAINT fk_vehicle_driver FOREIGN KEY (driver_id)
        REFERENCES public.driver(id)
);

CREATE TABLE public.vehicle_assignment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id bigint NOT NULL,
    driver_id bigint NOT NULL,
    assigned_from timestamp with time zone DEFAULT now() NOT NULL,
    assigned_to timestamp with time zone,
    created_at timestamp(6) without time zone DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'::text) NOT NULL,
    CONSTRAINT ck_assignment_period CHECK (
        assigned_to IS NULL OR assigned_to > assigned_from
    ),
    CONSTRAINT vehicle_assignment_vehicle_id_fkey FOREIGN KEY (vehicle_id)
        REFERENCES public.vehicle(id),
    CONSTRAINT vehicle_assignment_driver_id_fkey FOREIGN KEY (driver_id)
        REFERENCES public.driver(id)
);

CREATE TABLE public.vehicle_service (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id uuid DEFAULT gen_random_uuid() NOT NULL,
    vehicle_id bigint NOT NULL,
    due_maintenance_date date NOT NULL,
    maintenance_type character varying(50) NOT NULL,
    service_status character varying(20) DEFAULT 'DUE'::character varying NOT NULL,
    created_at timestamp(6) without time zone DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'::text) NOT NULL,
    call_attempts integer DEFAULT 0 NOT NULL,
    CONSTRAINT fk_vehicle_service_vehicle FOREIGN KEY (vehicle_id)
        REFERENCES public.vehicle(id)
);

CREATE TABLE public.voice_bot_call_job (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id uuid DEFAULT gen_random_uuid() NOT NULL,
    service_id integer NOT NULL,
    correlation_id uuid NOT NULL,
    job_status character varying(30) DEFAULT 'PENDING'::character varying NOT NULL,
    callback_received boolean DEFAULT false NOT NULL,
    callback_payload_file_path text,
    created_at timestamp(6) without time zone DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'::text) NOT NULL,
    updated_at timestamp(6) without time zone DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'::text) NOT NULL,
    CONSTRAINT fk_voice_bot_call_job_service FOREIGN KEY (service_id)
        REFERENCES public.vehicle_service(id)
);

CREATE TABLE public.voice_bot_call_job_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id bigint NOT NULL,
    event_status character varying(20) NOT NULL,
    system_message character varying(500),
    event_occurred_at timestamp(6) without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_call_job_event_job FOREIGN KEY (job_id)
        REFERENCES public.voice_bot_call_job(id)
);

-- ============================================================
-- INDEXES
-- ============================================================

CREATE INDEX ix_driver_language
    ON public.driver USING btree (preferred_language_id);

CREATE INDEX ix_assignment_driver
    ON public.vehicle_assignment USING btree (driver_id);

CREATE UNIQUE INDEX uq_assignment_one_current
    ON public.vehicle_assignment USING btree (vehicle_id)
    WHERE assigned_to IS NULL;

CREATE INDEX ix_vehicle_service_vehicle
    ON public.vehicle_service USING btree (vehicle_id);

CREATE INDEX ix_voice_bot_call_job_correlation
    ON public.voice_bot_call_job USING btree (correlation_id);

CREATE INDEX ix_voice_bot_call_job_service
    ON public.voice_bot_call_job USING btree (service_id);

CREATE INDEX ix_voice_bot_call_job_event_job
    ON public.voice_bot_call_job_event USING btree (job_id);

CREATE INDEX ix_voice_bot_call_job_event_status
    ON public.voice_bot_call_job_event USING btree (event_status);

-- PostgreSQL exclusion constraint: one vehicle cannot have overlapping assignments.
ALTER TABLE ONLY public.vehicle_assignment
    ADD CONSTRAINT ex_vehicle_assignment_no_overlap
    EXCLUDE USING gist (
        vehicle_id WITH =,
        tstzrange(assigned_from, assigned_to, '[)') WITH &&
    );

