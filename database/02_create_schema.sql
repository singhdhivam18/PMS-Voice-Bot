CREATE OR REPLACE VIEW public.v_pms_call_queue AS
SELECT
    vs.id AS vehicle_service_id,
    vs.external_id AS service_external_id,
    vs.due_maintenance_date,
    vs.maintenance_type,
    vs.call_attempts,
    v.id AS vehicle_id,
    v.registration_no,
    d.id AS driver_id,
    d.name AS driver_name,
    d.phone AS driver_phone,
    l.id AS language_id,
    l.code AS preferred_language,
    l.name AS preferred_language_name,
    d.language_source
FROM public.vehicle_service vs
JOIN public.vehicle v
    ON v.id = vs.vehicle_id
JOIN public.vehicle_assignment a
    ON a.vehicle_id = v.id
   AND a.assigned_to IS NULL
JOIN public.driver d
    ON d.id = a.driver_id
JOIN public.language l
    ON l.id = d.preferred_language_id
WHERE vs.service_status = 'DUE'
  AND d.do_not_call = false;

CREATE OR REPLACE VIEW public.v_pms_needs_attention AS
SELECT
    vs.id AS vehicle_service_id,
    v.registration_no,
    vs.due_maintenance_date,
    CASE
        WHEN a.id IS NULL THEN 'no current driver'::text
        WHEN d.do_not_call THEN 'driver is do_not_call'::text
        ELSE NULL::text
    END AS reason
FROM public.vehicle_service vs
JOIN public.vehicle v
    ON v.id = vs.vehicle_id
LEFT JOIN public.vehicle_assignment a
    ON a.vehicle_id = v.id
   AND a.assigned_to IS NULL
LEFT JOIN public.driver d
    ON d.id = a.driver_id
WHERE vs.service_status = 'DUE'
  AND (a.id IS NULL OR d.do_not_call);

COMMIT;
